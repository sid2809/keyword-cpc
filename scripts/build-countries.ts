/**
 * Regenerates src/lib/countries.ts from Google's geo targets CSV.
 *
 * Google publishes the full list of Google Ads locations as a zipped CSV:
 *   https://developers.google.com/google-ads/api/data/geotargets
 * Download "Latest zipped CSV", unzip it, then run:
 *   npm run build:countries -- path/to/geotargets-YYYY-MM-DD.csv
 *
 * Only rows with Target Type "Country" and Status "Active" are kept. The
 * script refuses to write if the file doesn't look like Google's format, so a
 * wrong file can't silently empty the list.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { basename, resolve } from "node:path";
import Papa from "papaparse";

const EXPECTED = ["Criteria ID", "Name", "Canonical Name", "Parent ID", "Country Code", "Target Type", "Status"];
const OUT = resolve(import.meta.dirname, "../src/lib/countries.ts");

function fail(message: string): never {
  console.error(`build-countries: ${message}`);
  process.exit(1);
}

const file = process.argv[2];
if (!file) fail("pass the path to Google's geotargets CSV.");

const parsed = Papa.parse<Record<string, string>>(readFileSync(file, "utf8"), {
  header: true,
  skipEmptyLines: true,
});
if (parsed.errors.length > 0) fail(`CSV parse errors: ${JSON.stringify(parsed.errors.slice(0, 3))}`);
const columns = parsed.meta.fields ?? [];
if (EXPECTED.some((c) => !columns.includes(c))) fail(`unexpected columns: ${columns.join(", ")}`);

const countries = parsed.data
  .filter((r) => r["Target Type"] === "Country" && r["Status"] === "Active")
  .map((r) => ({ id: r["Criteria ID"], name: r["Name"], code: r["Country Code"] }));

if (countries.length < 150) fail(`only ${countries.length} countries found; is this the right file?`);
for (const c of countries) {
  if (!/^\d+$/.test(c.id) || !c.name || !/^[A-Z]{2}$/.test(c.code)) fail(`bad row: ${JSON.stringify(c)}`);
}
const ids = new Set(countries.map((c) => c.id));
if (ids.size !== countries.length) fail("duplicate Criteria IDs");

countries.sort((a, b) => a.name.localeCompare(b.name, "en"));

const source = basename(file);
const body = countries
  .map((c) => `  { id: "geoTargetConstants/${c.id}", name: ${JSON.stringify(c.name)}, code: "${c.code}" },`)
  .join("\n");

writeFileSync(
  OUT,
  `/**
 * Google Ads countries (target type "Country", status "Active").
 *
 * GENERATED by scripts/build-countries.ts from Google's ${source}
 * (${countries.length} countries). Do not edit by hand: download a newer file from
 * https://developers.google.com/google-ads/api/data/geotargets and run
 *   npm run build:countries -- path/to/geotargets-YYYY-MM-DD.csv
 */

export type Country = { id: string; name: string; code: string };

export const COUNTRIES_SOURCE = ${JSON.stringify(source)};

export const COUNTRIES: readonly Country[] = [
${body}
];

const BY_ID = new Map(COUNTRIES.map((c) => [c.id, c]));

/** The country for a geo target id ("geoTargetConstants/2840"), if it is one. */
export function countryById(id: string): Country | undefined {
  return BY_ID.get(id);
}
`,
);
console.log(`build-countries: wrote ${countries.length} countries from ${source} to src/lib/countries.ts`);
